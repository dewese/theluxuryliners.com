// Writes dist/_headers from worker/headers.ts (the same set the Worker sends), plus caching:
// hashed build files for a year, images for a week, pages revalidated. /admin/ (Decap CMS) loads
// its editor from a CDN, so the site CSP is removed there and replaced by its own: only the pinned
// Decap file (which also carries an SRI hash in public/admin/index.html), no plugins, no <base>.
// The editor signs in through a cross-origin OAuth popup that hands the token back with
// window.opener.postMessage, so /admin/* uses COOP same-origin-allow-popups (audit-security
// round 1, S5); every other page keeps same-origin.
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECURITY_HEADERS } from '../worker/headers.ts';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const block = (path, headers) => [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n');
export const ADMIN_CSP = "default-src 'self'; script-src 'self' 'unsafe-eval' https://unpkg.com/decap-cms@3.17.1/dist/decap-cms.js; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https:; connect-src 'self' https://api.github.com https://raw.githubusercontent.com https://github.com; object-src 'none'; base-uri 'self'; frame-ancestors 'none'";
export const HEADERS_FILE = [
  '# Generated by scripts/build-headers.mjs from worker/headers.ts. Do not edit by hand.',
  block('/*', SECURITY_HEADERS),
  block('/_astro/*', { 'Cache-Control': 'public, max-age=31536000, immutable' }),
  block('/img/*', { 'Cache-Control': 'public, max-age=604800' }),
  ['/admin/*', '  ! Content-Security-Policy', `  Content-Security-Policy: ${ADMIN_CSP}`, '  ! Cross-Origin-Opener-Policy', '  Cross-Origin-Opener-Policy: same-origin-allow-popups', '  X-Robots-Tag: noindex'].join('\n'),
  '',
].join('\n\n');
writeFileSync(join(site, 'dist', '_headers'), HEADERS_FILE);
console.log('build-headers: dist/_headers written');
